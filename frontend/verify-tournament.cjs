const {buildSync} = require('esbuild');
const source = `
import assert from 'node:assert/strict';
import {createElement} from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {Knockout} from './src/Knockout';
import {clubs} from './src/clubs';
import {createDemoTournament,roundDate} from './src/demoTournament';
import {clubZones} from './src/zones';
import {groupFixtureByZone,quintaDemoMatches} from './src/fixtureZones';
import {projectKnockout,validPairings} from './src/knockoutProjection';
import {buildStandings} from './src/standings';
const matches=createDemoTournament();
assert.deepEqual(groupFixtureByZone(quintaDemoMatches,'Quinta').map(group=>[group.id,group.matches.length]),[['north',1],['south',1],['interzonal',1]]);
assert.deepEqual(groupFixtureByZone([],'Sexta').map(group=>group.id),['north','south']);
const unassigned={...quintaDemoMatches[0],homeClubId:undefined};
assert.equal(groupFixtureByZone([unassigned],'Quinta').at(-1).id,'unassigned');
const grouped=groupFixtureByZone(matches,'TorneoDemo').flatMap(group=>group.matches);
assert.equal(grouped.length,matches.length);
assert.equal(new Set(grouped.map(match=>match.id)).size,matches.length);
assert.deepEqual(clubZones.map(zone=>zone.clubIds.length),[13,13,4]);
assert.equal(new Set(clubZones.flatMap(zone=>zone.clubIds)).size,30);
assert(clubZones.flatMap(zone=>zone.clubIds).every(id=>clubs.some(club=>club.id===id)));
assert.equal(clubs.length,30);
assert.equal(matches.length,435);
assert.equal(new Set(matches.map(m=>m.id)).size,435);
const pairs=new Set();
for(let round=1;round<=29;round++) {
 const games=matches.filter(m=>m.round===round);
 assert.equal(games.length,15);
 assert.equal(new Set(games.flatMap(m=>[m.homeClubId,m.awayClubId])).size,30);
 for(const game of games) {
   assert.notEqual(game.homeClubId,game.awayClubId);
   const pair=[game.homeClubId,game.awayClubId].sort().join('|');
   assert(!pairs.has(pair)); pairs.add(pair);
 }
}
for(const club of clubs) {
 const games=matches.filter(m=>m.homeClubId===club.id||m.awayClubId===club.id);
 assert.equal(games.length,29);
 assert.equal(games.filter(m=>m.status==='Finalizado').length,2);
 const home=games.filter(m=>m.homeClubId===club.id).length;
 assert(home===14||home===15,club.name+' home count '+home);
}
const rows=buildStandings(matches);
assert.equal(rows.length,30);
assert(rows.every(r=>r.played===2));
assert.equal(rows.reduce((s,r)=>s+r.gf,0),rows.reduce((s,r)=>s+r.ga,0));
const changed=matches.map((m,i)=>i===30?{...m,status:'Finalizado' as const,homeGoals:3,awayGoals:1}:m);
assert.equal(buildStandings(changed).reduce((s,r)=>s+r.played,0),62);
assert.equal(roundDate(29),'2027-05-23');
const otherDivision=matches.map(match=>({...match,category:'Quinta'}));
assert.equal(projectKnockout(otherDivision).pairs.length,0);
assert.equal(projectKnockout([...matches,...otherDivision],'Quinta').pairs.length,8);
assert.equal(projectKnockout([...matches,...otherDivision],'Quinta').zones[0][0].played,2);
assert.equal(projectKnockout([], 'Quinta').pairs.length,0);
const projection=projectKnockout(matches);
assert.equal(projection.pairs.length,8);
assert.equal(projection.completedRounds,2);
assert.equal(projection.lastRound,29);
assert.equal(projection.complete,false);
const entrants=projection.pairs.flatMap(pair=>pair.map(team=>team.club.id));
assert.equal(new Set(entrants).size,16);
assert(projection.pairs.every((pair,index)=>pair[0].rank===index+1&&pair[1].rank===8-index));
assert(projection.pairs.every(pair=>pair[0].zone!==pair[1].zone));
assert(entrants.every(id=>!clubZones[2].clubIds.includes(id)));
assert(validPairings(entrants,entrants));
assert(!validPairings([...entrants.slice(0,-1),entrants[0]],entrants));
assert(!validPairings(entrants.slice(1),entrants));
const finished=matches.map(match=>({...match,status:'Finalizado' as const,homeGoals:0,awayGoals:0}));
assert(projectKnockout(finished).complete);
assert.equal(projectKnockout(finished).completedRounds,29);
const changedProjection=projectKnockout(changed);
const home=changedProjection.zones.flat().find(team=>team.team===changed[30].home);
const prior=projection.zones.flat().find(team=>team.team===changed[30].home);
if(home&&prior) assert.equal(home.points,prior.points+3);
const markup=renderToStaticMarkup(createElement(Knockout,{matches}));
assert.equal((markup.match(/class="knockout-tie"/g)||[]).length,15);
assert(!markup.includes('<select'));
assert(!markup.includes('<button'));
assert(!markup.includes('Camino a la final'));
assert(markup.includes('Octavos de final'));
assert(markup.includes('Clasificaci'));
console.log('OK: projection, interzonal pairings, winners pool and progression;');
console.log('OK: 30 clubes, 29 fechas, 435 cruces únicos, localías equilibradas, tabla y corrección de resultado.');
`;
const result = buildSync({stdin:{contents:source,resolveDir:__dirname,loader:'ts'},bundle:true,platform:'node',format:'cjs',write:false});
new Function('require',result.outputFiles[0].text)(require);
